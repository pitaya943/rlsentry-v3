-- Meant to hide unfinished posts from the public; private posts were added later.
create table public.posts (
  id bigint generated by default as identity primary key,
  title text not null,
  status text not null default 'draft',
  constraint posts_status check (status in ('draft', 'published', 'private'))
);
alter table public.posts enable row level security;

create policy "Everything but drafts is public." on public.posts
  for select using (status <> 'draft');
