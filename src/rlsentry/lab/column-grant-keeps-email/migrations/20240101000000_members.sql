-- Meant to keep the password reset token away from the public; the email was granted back with the rest.
create table public.members (
  id bigint generated by default as identity primary key,
  display_name text not null,
  email text not null,
  reset_token text
);
revoke select on public.members from anon;
grant select (id, display_name, email) on public.members to anon;
