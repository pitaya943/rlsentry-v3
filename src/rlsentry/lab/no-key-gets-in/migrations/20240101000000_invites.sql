-- Meant to keep invites from browsers holding the project's key; a request with no key at all was forgotten.
create table public.invites (
  id bigint generated by default as identity primary key,
  email text not null,
  code text not null
);
alter table public.invites enable row level security;

create policy "Only requests without a token issuer." on public.invites
  for select using ((auth.jwt() ->> 'iss') is null);
